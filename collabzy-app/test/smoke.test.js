const test=require('node:test');
const assert=require('node:assert/strict');
const {spawn}=require('node:child_process');
const net=require('node:net');
const path=require('node:path');
const os=require('node:os');
const fs=require('node:fs');
test('Collabzy API supports registration, campaign publishing and application workflow',async(t)=>{
  const server=net.createServer();
  await new Promise((resolve,reject)=>server.listen(0,'127.0.0.1',resolve).once('error',reject));
  const port=server.address().port;
  await new Promise(resolve=>server.close(resolve));
  const dbPath=path.join(os.tmpdir(),'collabzy-test-'+process.pid+'-'+Date.now()+'.db');
  const child=spawn(process.execPath,['src/server.js'],{cwd:path.join(__dirname,'..'),env:{...process.env,NODE_ENV:'test',PORT:String(port),JWT_SECRET:'test-secret-with-more-than-32-characters-12345',DATABASE_PATH:dbPath},stdio:['ignore','pipe','pipe']});
  let logs='';
  child.stdout.on('data',d=>logs+=d.toString());child.stderr.on('data',d=>logs+=d.toString());
  t.after(async()=>{child.kill('SIGTERM');await new Promise(resolve=>{if(child.exitCode!==null)return resolve();child.once('exit',resolve);setTimeout(resolve,1500)});for(const ext of ['', '-shm','-wal'])try{fs.unlinkSync(dbPath+ext)}catch{}});
  const base='http://127.0.0.1:'+port;
  let ready=false;
  for(let i=0;i<80;i++){if(child.exitCode!==null)break;try{const r=await fetch(base+'/api/health');if(r.ok){ready=true;break}}catch{}await new Promise(r=>setTimeout(r,250))}
  assert.equal(ready,true,'server should start; logs: '+logs);
  const health=await (await fetch(base+'/api/health')).json();
  assert.equal(health.ok,true);
  const campaigns=(await (await fetch(base+'/api/campaigns')).json()).campaigns;
  assert.ok(campaigns.length>=1,'sample campaigns should be available');
  const email='creator'+Date.now()+'@example.com';
  const reg=await fetch(base+'/api/auth/register',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({name:'Test Creator',email,password:'TestPassword123!',role:'creator'})});
  assert.equal(reg.status,201);
  const creator=await reg.json();assert.ok(creator.token);
  const instagramSetup=await fetch(base+'/api/instagram/connect',{headers:{authorization:'Bearer '+creator.token}});
  assert.equal(instagramSetup.status,503,'Instagram should clearly report missing Meta credentials in test environment');
  const duplicate=await fetch(base+'/api/auth/register',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({name:'Test Creator',email,password:'TestPassword123!',role:'creator'})});
  assert.equal(duplicate.status,409);
  const campaignId=campaigns[0].id;
  const save=await fetch(base+'/api/campaigns/'+campaignId+'/save',{method:'POST',headers:{authorization:'Bearer '+creator.token}});
  assert.equal(save.status,200);
  const saved=(await (await fetch(base+'/api/saved-campaigns',{headers:{authorization:'Bearer '+creator.token}})).json()).campaigns;
  assert.equal(saved.length,1,'creator should be able to save a campaign');
  const unsave=await fetch(base+'/api/campaigns/'+campaignId+'/save',{method:'DELETE',headers:{authorization:'Bearer '+creator.token}});
  assert.equal(unsave.status,200);
  const savedAfter=(await (await fetch(base+'/api/saved-campaigns',{headers:{authorization:'Bearer '+creator.token}})).json()).campaigns;
  assert.equal(savedAfter.length,0,'creator should be able to remove a saved campaign');
  const apply=await fetch(base+'/api/campaigns/'+campaignId+'/apply',{method:'POST',headers:{'content-type':'application/json',authorization:'Bearer '+creator.token},body:JSON.stringify({pitch:'I am a good fit',proposed_rate:2500})});
  assert.equal(apply.status,201);
  const applications=(await (await fetch(base+'/api/applications',{headers:{authorization:'Bearer '+creator.token}})).json()).applications;
  assert.equal(applications.length,1);assert.equal(applications[0].status,'pending');
  const login=await fetch(base+'/api/auth/login',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({email,password:'TestPassword123!'})});
  assert.equal(login.status,200);
  const invalid=await fetch(base+'/api/auth/register',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({name:'No email',email:'bad',password:'TestPassword123!',role:'creator'})});
  assert.equal(invalid.status,400);
});
